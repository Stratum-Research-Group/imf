"""Move papers into phase folders and docs into typed subfolders; regenerate indexes."""
import glob,os,re,subprocess
def mv(a,b):
    os.makedirs(os.path.dirname(b),exist_ok=True); subprocess.check_call(['git','mv',a,b])
PH=[(1,78,'phase_1_core_architecture'),(79,130,'phase_2_formal_verification_and_math_physics'),
 (131,199,'phase_3_poincare_hyperbolic_kernels'),(200,285,'phase_4_soliton_hierarchies'),
 (286,471,'phase_5_certified_scaling_lie_geometry_io'),(472,600,'phase_6_blackwell_kernels_and_dma_engines')]
rows=[]
for f in sorted(glob.glob('papers/*.md')):
    b=os.path.basename(f)
    m=re.match(r'(?:paper_)?(\d+)_',b)
    if b.startswith('appendix_paper_100'): n=100
    elif m: n=int(m.group(1))
    else: continue
    d=next(d for a,z,d in PH if a<=n<=z); mv(f,f'papers/{d}/{b}'); rows.append((n,d,b))
mv('papers/IMF_MATHEMATICAL_FOUNDATIONS_WHITEPAPER.md','docs/whitepapers/IMF_MATHEMATICAL_FOUNDATIONS_WHITEPAPER.md')
mv('papers/roadmap_century_milestone_94_100.md','docs/roadmaps/roadmap_century_milestone_94_100.md')
D={'specs':['MICROARCHITECTURAL_KERNELS_SPECIFICATION.md','Stereochemical_Chiral_Model.md','COGNITIVE_WORKFLOWS.md'],
 'manuals':['IMF_COMPLETE_ARCHITECTURE_MANUAL.md'],
 'reports':['BENCHMARK_COGNITIVE_FLOW.md','IMF_VERIFICATION_REPORT.md','RIGOROUS_EVALUATION_REPORT.md'],
 'benchmarks':['counter_rotating_vortex_benchmark.json','leech_coset_expansion_benchmark.json','long_context_mqar_100b_benchmark.json','speculative_virtual_cell_100b_benchmark.json','tournament_consensus_benchmark.json','SUBBIT_QUANTIZATION_FIDELITY_REPORT.json','VRAM_SWAPPER_LATENCY_REPORT.json'],
 'manifests':['frontier_cross_distillation_manifest.json','scaffold_manifest_100b_leech.json']+[os.path.basename(x) for x in glob.glob('docs/release_manifest_*.json')]}
moved={}
for k,fs in D.items():
    for x in fs:
        if os.path.exists('docs/'+x): mv('docs/'+x,f'docs/{k}/{x}'); moved[x]=f'docs/{k}/{x}'
if os.path.exists('docs/manuals/IMF_BIBLE.md'): mv('docs/manuals/IMF_BIBLE.md','docs/manuals/IMF_BIBLE.md'); moved['manual/IMF_BIBLE.md']='docs/manuals/IMF_BIBLE.md'
# fix hard-coded paths in code/docs
for src in glob.glob('scripts/*.py')+glob.glob('imf/**/*.py',recursive=True)+['README.md']:
    try: s=open(src).read()
    except: continue
    o=s
    for x,new in moved.items(): s=s.replace('docs/'+x,new)
    if s!=o: open(src,'w').write(s); print('patched',src)
# indexes
def meta(path):
    t=open(path).read().split('\n'); g=lambda k:next((l.split(':**',1)[1].strip() for l in t if l.startswith(f'**{k}:**')),'')
    return t[0].lstrip('# ').strip(),g('Paper Type'),g('Status')
rows.sort(); out=["# IMF Papers Index\n","Generated by `scripts/reorganize_repo.py` from each paper's own header. Status reflects in-text evidence only (see `THEORETICAL_DRAFTS.md`).\n"]
cur=None
for n,d,b in rows:
    if d!=cur:
        cur=d; out+=[f"\n## {d}\n","| Paper | Type | Status |","|:--|:--|:--|"]
    t,pt,st=meta(f'papers/{d}/{b}'); out.append(f"| [{t}]({d}/{b}) | {pt} | {st} |")
open('papers/README.md','w').write('\n'.join(out)+'\n')
dr=[(n,d,b) for n,d,b in rows if 'Theoretical Draft' in meta(f'papers/{d}/{b}')[2]]
open('papers/THEORETICAL_DRAFTS.md','w').write("# Theoretical Drafts\n\nNo in-text Lean proof or benchmark; unverified.\n\n"+'\n'.join(f"- [{b}]({d}/{b})" for n,d,b in dr)+'\n')
print(len(rows),len(dr))
